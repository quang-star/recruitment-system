"""Build the data-free Core codegen schema from versioned SQL column DDL.

Flyway's Java data migration cannot run in jOOQ's H2 schema interpreter. This
projection contains final columns/keys only; PostgreSQL migrations remain canonical.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MIGRATIONS = ROOT / "core-service/src/main/resources/db/migration"
OUTPUT = ROOT / "core-service/src/main/resources/db/codegen/core-schema.sql"
TYPE = r"(?:VARCHAR\s*\(\s*\d+\s*\)|CHAR\s*\(\s*\d+\s*\)|NUMERIC\s*\(\s*\d+\s*,\s*\d+\s*\)|BIGINT|SMALLINT|INTEGER|TIMESTAMPTZ|TIMESTAMP|BOOLEAN|UUID|JSONB|JSON|TEXT|DATE|BYTEA)"
tables = {}
keys = {}
for path in sorted(MIGRATIONS.glob("V*.sql"), key=lambda p: int(p.name.split("__")[0][1:])):
    sql = re.sub(r"/\*.*?\*/|--[^\n]*", "", path.read_text(encoding="utf-8"), flags=re.S)
    for match in re.finditer(r"CREATE TABLE(?: IF NOT EXISTS)? (\w+)\s*\((.*?)\n\);", sql, re.S | re.I):
        name, body = match.groups()
        columns = {}
        for column in re.finditer(r"^\s*(\w+)\s+(" + TYPE + r")(.*)$", body, re.M | re.I):
            field, kind, options = column.groups()
            if field.upper() in {"CONSTRAINT", "FOREIGN", "PRIMARY", "UNIQUE", "CHECK"}:
                continue
            columns[field] = [kind.upper(), "NOT NULL" in options.upper(), "GENERATED" in options.upper()]
            if "PRIMARY KEY" in options.upper():
                keys[name] = [field]
        composite = re.search(r"PRIMARY KEY\s*\(([^)]+)\)", body, re.I)
        if composite:
            keys[name] = [field.strip() for field in composite[1].split(",")]
        tables[name] = columns
    for table, actions in re.findall(r"ALTER TABLE (\w+)\s+(.*?);", sql, re.S | re.I):
        for field, kind, options in re.findall(r"ADD COLUMN (?:IF NOT EXISTS )?(\w+)\s+(" + TYPE + r")([^\n]*)", actions, re.I):
            tables[table][field] = [kind.upper(), "NOT NULL" in options.upper(), False]
    for table, field, kind in re.findall(r"ALTER TABLE (\w+) ALTER COLUMN (\w+) TYPE (" + TYPE + r")", sql, re.I):
        tables[table][field][0] = kind.upper()
    for table, field in re.findall(r"ALTER TABLE (\w+) ALTER COLUMN (\w+) DROP NOT NULL", sql, re.I):
        tables[table][field][1] = False
    for table, field in re.findall(r"ALTER TABLE (\w+) ALTER COLUMN (\w+) SET NOT NULL", sql, re.I):
        tables[table][field][1] = True
    for table, field in re.findall(r"ALTER TABLE (\w+) DROP COLUMN (\w+)", sql, re.I):
        tables[table].pop(field)
    for table, before, after in re.findall(r"ALTER TABLE (\w+) RENAME COLUMN (\w+) TO (\w+)", sql, re.I):
        tables[table][after] = tables[table].pop(before)

tables["job_category_catalog"]["id"][2] = True
lines = ["-- Generated by scripts/generate-core-jooq-schema.py; do not apply to a database.",
         "-- Flyway SQL/Java migrations own the real PostgreSQL schema and constraints.", ""]
for table, columns in tables.items():
    fields = []
    for field, (kind, required, identity) in columns.items():
        fields.append("    " + field + " " + kind + (" GENERATED BY DEFAULT AS IDENTITY" if identity else "")
                      + (" NOT NULL" if required else ""))
    if table in keys:
        fields.append("    PRIMARY KEY (" + ", ".join(keys[table]) + ")")
    lines.extend(["CREATE TABLE " + table + " (", ",\n".join(fields), ");", ""])
OUTPUT.parent.mkdir(parents=True, exist_ok=True)
OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(tables)} tables)")
