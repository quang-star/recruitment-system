/*
 * Authentication data is intentionally isolated from recruitment data.
 * Raw credentials and bearer tokens must never be stored in this database.
 */

ALTER TABLE auth_users
    ADD COLUMN deleted_at TIMESTAMPTZ;

UPDATE auth_users
SET deleted_at = updated_at
WHERE status = 'DELETED' AND deleted_at IS NULL;

ALTER TABLE auth_users
    ADD CONSTRAINT ck_auth_users_email_not_blank
        CHECK (char_length(btrim(email)) > 0),
    ADD CONSTRAINT ck_auth_users_normalized_email_not_blank
        CHECK (char_length(btrim(normalized_email)) > 0),
    ADD CONSTRAINT ck_auth_users_status
        CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED', 'DELETED')),
    ADD CONSTRAINT ck_auth_users_version
        CHECK (version >= 0),
    ADD CONSTRAINT ck_auth_users_timestamps
        CHECK (updated_at >= created_at),
    ADD CONSTRAINT ck_auth_users_deleted_at
        CHECK (
            (status = 'DELETED' AND deleted_at IS NOT NULL)
            OR (status <> 'DELETED' AND deleted_at IS NULL)
        );

CREATE TABLE password_credentials (
    user_id BIGINT PRIMARY KEY,
    password_hash TEXT NOT NULL,
    hash_algorithm VARCHAR(32) NOT NULL,
    password_changed_at TIMESTAMPTZ NOT NULL,
    failed_attempt_count INTEGER NOT NULL DEFAULT 0,
    last_failed_at TIMESTAMPTZ,
    locked_until TIMESTAMPTZ,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT fk_password_credentials_user
        FOREIGN KEY (user_id) REFERENCES auth_users (id) ON DELETE CASCADE,
    CONSTRAINT ck_password_credentials_hash_not_blank
        CHECK (char_length(password_hash) >= 20),
    CONSTRAINT ck_password_credentials_algorithm_not_blank
        CHECK (char_length(btrim(hash_algorithm)) > 0),
    CONSTRAINT ck_password_credentials_failed_attempt_count
        CHECK (failed_attempt_count >= 0),
    CONSTRAINT ck_password_credentials_version
        CHECK (version >= 0),
    CONSTRAINT ck_password_credentials_timestamps
        CHECK (
            password_changed_at >= created_at
            AND updated_at >= created_at
            AND (last_failed_at IS NULL OR last_failed_at >= created_at)
        )
);

COMMENT ON COLUMN password_credentials.password_hash IS
    'Self-describing Argon2id/bcrypt/PBKDF2 hash; never a plaintext or reversible password.';

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    system_role BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT uk_roles_code UNIQUE (code),
    CONSTRAINT ck_roles_code_format
        CHECK (code ~ '^[A-Z][A-Z0-9_]{1,63}$'),
    CONSTRAINT ck_roles_name_not_blank
        CHECK (char_length(btrim(name)) > 0),
    CONSTRAINT ck_roles_status
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_roles_version
        CHECK (version >= 0),
    CONSTRAINT ck_roles_timestamps
        CHECK (updated_at >= created_at)
);

CREATE TABLE permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    code VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_permissions_code UNIQUE (code),
    CONSTRAINT ck_permissions_code_format
        CHECK (code ~ '^[a-z][a-z0-9_.:-]{2,99}$'),
    CONSTRAINT ck_permissions_description_not_blank
        CHECK (char_length(btrim(description)) > 0)
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    assigned_by_user_id BIGINT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

