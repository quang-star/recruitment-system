CREATE TABLE cv_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_user_id BIGINT NOT NULL,
    title VARCHAR(160) NOT NULL,
    template_id VARCHAR(30) NOT NULL,
    accent_color VARCHAR(7) NOT NULL,
    section_order JSONB NOT NULL,
    content_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_cv_drafts_title CHECK (char_length(btrim(title)) BETWEEN 1 AND 160),
    CONSTRAINT ck_cv_drafts_template CHECK (template_id IN ('classic', 'modern', 'minimal')),
    CONSTRAINT ck_cv_drafts_accent_color CHECK (accent_color ~ '^#[0-9a-fA-F]{6}$'),
    CONSTRAINT ck_cv_drafts_version CHECK (version >= 0),
    CONSTRAINT ck_cv_drafts_timestamps CHECK (updated_at >= created_at)
);

CREATE INDEX ix_cv_drafts_candidate_updated ON cv_drafts (candidate_user_id, updated_at DESC, id DESC);
