-- Operating approval is separate from legal verification. No existing company
-- or job is approved, closed or rewritten by this migration.
CREATE TABLE company_review_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
    actor_user_id BIGINT NOT NULL,
    action VARCHAR(20) NOT NULL CHECK (action = 'APPROVE'),
    from_status VARCHAR(20) NOT NULL CHECK (from_status = 'PENDING'),
    to_status VARCHAR(20) NOT NULL CHECK (to_status = 'ACTIVE'),
    version BIGINT NOT NULL CHECK (version > 0),
    reason VARCHAR(1000) NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 1 AND 1000),
    correlation_id UUID NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_company_review_version UNIQUE (company_id, version)
);

CREATE INDEX ix_company_review_history ON company_review_history (company_id, occurred_at DESC, id DESC);
CREATE INDEX ix_companies_review_queue ON companies (status, created_at, id);
