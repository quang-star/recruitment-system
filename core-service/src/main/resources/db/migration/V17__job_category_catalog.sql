CREATE TABLE job_category_catalog (
    id UUID PRIMARY KEY,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('INDUSTRY','SPECIALIZATION','POSITION')),
    parent_id UUID REFERENCES job_category_catalog(id) ON DELETE RESTRICT,
    name VARCHAR(160) NOT NULL CHECK (length(btrim(name)) > 0),
    normalized_name VARCHAR(160) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','ACTIVE','MERGED','REJECTED')),
    merged_into_id UUID REFERENCES job_category_catalog(id) ON DELETE RESTRICT,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((kind='INDUSTRY' AND parent_id IS NULL) OR (kind<>'INDUSTRY' AND parent_id IS NOT NULL)),
    CHECK ((status='MERGED' AND merged_into_id IS NOT NULL) OR (status<>'MERGED' AND merged_into_id IS NULL)),
    CHECK (id IS DISTINCT FROM parent_id AND id IS DISTINCT FROM merged_into_id)
);
CREATE UNIQUE INDEX uk_job_category_current_root_name ON job_category_catalog(kind,normalized_name)
    WHERE parent_id IS NULL AND status IN ('PENDING','ACTIVE');
CREATE UNIQUE INDEX uk_job_category_current_child_name ON job_category_catalog(kind,parent_id,normalized_name)
    WHERE parent_id IS NOT NULL AND status IN ('PENDING','ACTIVE');
CREATE INDEX ix_job_category_parent_status ON job_category_catalog(parent_id,status);

CREATE TABLE job_category_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id UUID NOT NULL REFERENCES job_category_catalog(id) ON DELETE RESTRICT,
    actor_user_id UUID NOT NULL,
    action VARCHAR(20) NOT NULL,
    before_state JSONB,
    after_state JSONB NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_job_category_history ON job_category_history(category_id,id);

