/** Maps legacy 63-province names or observed variants to the 34-province administrative list. */
export function normalizeProvinceName(raw?: string | null): string {
  const trimmed = (raw ?? "").trim();
  if (!trimmed) return "";
  const mapped = LEGACY_PROVINCE_MAP[trimmed.toLowerCase()];
  if (mapped) return mapped;
  const exact = VIETNAM_PROVINCES.find((p) => p.toLowerCase() === trimmed.toLowerCase());
  return exact ?? trimmed;
}
